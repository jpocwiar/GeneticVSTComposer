"""Rebuild the embedded harmonic-transition prior using only Python's standard library.

The CC BY 4.0 UCI source is vendored under data/harmony/uci-bach. No network,
Python, or training is needed to build or run the plugin. --download explicitly
refreshes the pinned source; --check verifies the checked-in generated header.
"""
import argparse
import collections
import csv
import hashlib
import io
import math
from pathlib import Path
import re
import urllib.request
import zipfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'data/harmony/uci-bach'
OUTPUT = ROOT / 'JUCE/GeneticVSTComposer-JUCE/Source/HarmonyModelData.h'
URL = 'https://archive.ics.uci.edu/static/public/298/bach+choral+harmony.zip'
ZIP_SHA = '6b5a0d52262839ead7605b8b95f455d464299a245638f44990fcb443bd0f4aaf'
DATA_SHA = '81554b251ca9183686b0aa207f214ea92fd48dbb73ef89fa1678a257d3a57457'
LABEL = re.compile(r'([A-G])([#b]?)_?([Mmd])([467]?)')
PITCHES = dict(C=0, D=2, E=4, F=5, G=7, A=9, B=11)


def load_sequences(path):
    payload = path.read_bytes()
    if hashlib.sha256(payload).hexdigest() != DATA_SHA:
        raise ValueError('UCI source checksum differs from the pinned release')
    sequences = collections.OrderedDict()
    events = 0
    last_events = {}
    for row in csv.reader(io.StringIO(payload.decode('ascii'))):
        if len(row) != 17:
            raise ValueError('Expected exactly 17 fields per event')
        piece, event = row[0].strip(), int(row[1])
        if event <= last_events.get(piece, 0):
            raise ValueError('Duplicate or unordered event within a source ID')
        last_events[piece] = event
        match = LABEL.fullmatch(row[-1].strip())
        if not match:
            raise ValueError('Unsupported chord annotation: ' + row[-1])
        letter, accidental, family, _ = match.groups()
        root = (PITCHES[letter] + {'': 0, '#': 1, 'b': -1}[accidental]) % 12
        chord = (root, {'M': 0, 'm': 1, 'd': 2}[family])
        sequence = sequences.setdefault(piece, [])
        # Changes of inversion, extension or metrical subdivision do not count
        # as new root/triad-family events. Never join across source IDs.
        if not sequence or sequence[-1] != chord:
            sequence.append(chord)
        events += 1
    return sequences, events


def counts(sequences):
    first = [[0] * 36 for _ in range(3)]
    context = [[0] * 36 for _ in range(36)]
    for sequence in sequences:
        for i in range(1, len(sequence)):
            root, family = sequence[i]
            prior_root, prior_family = sequence[i - 1]
            outcome = ((root - prior_root) % 12) * 3 + family
            first[prior_family][outcome] += 1
            if i >= 2:
                interval = (prior_root - sequence[i - 2][0]) % 12
                context[interval * 3 + prior_family][outcome] += 1
    return first, context


def evaluate(training, held_out):
    first, context = counts(training)
    loss_first = loss_context = 0.0
    total = 0
    for sequence in held_out:
        for i in range(2, len(sequence)):
            root, family = sequence[i]
            prior_root, prior_family = sequence[i - 1]
            outcome = ((root - prior_root) % 12) * 3 + family
            previous = (prior_root - sequence[i - 2][0]) % 12
            row = first[prior_family]
            p1 = (row[outcome] + 0.5) / (sum(row) + 18.0)
            row2 = context[previous * 3 + prior_family]
            p2 = (row2[outcome] + 6.0 * p1) / (sum(row2) + 6.0)
            loss_first -= math.log(p1)
            loss_context -= math.log(p2)
            total += 1
    return total, math.exp(loss_first / total), math.exp(loss_context / total)


def array(name, rows):
    body = ',\n'.join('    {' + ', '.join(map(str, row)) + '}' for row in rows)
    return 'inline constexpr uint16_t %s[%d][36] = {\n%s\n};\n' % (name, len(rows), body)


def build():
    sequences, events = load_sequences(SOURCE / 'jsbach_chorals_harmony.data')
    # Stable piece-level split prevents adjacent events leaking into validation.
    test_ids = {name for name in sequences if int(hashlib.sha256(name.encode('ascii')).hexdigest(), 16) % 5 == 0}
    held_out = [seq for name, seq in sequences.items() if name in test_ids]
    training = [seq for name, seq in sequences.items() if name not in test_ids]
    evaluated, first_perplexity, context_perplexity = evaluate(training, held_out)
    # After the held-out evaluation, deploy counts fitted to all source IDs.
    first, context = counts(sequences.values())
    changes = sum(map(sum, first))
    text = '''// Generated by scripts/train-harmony-model.py. Do not hand edit.
// Derived from Radicioni & Esposito (2014), UCI Bach Choral Harmony.
// https://doi.org/10.24432/C5B61F -- CC BY 4.0; see data/harmony/README.md.
// Root intervals and coarse major/minor/diminished families only; no song templates.
#pragma once
#include <cstdint>
namespace composer::harmony_model {
'''
    for name, value in [('sourceEvents', events), ('sourceSequences', len(sequences)),
                        ('transitions', changes), ('validationSequences', len(test_ids)),
                        ('validationTransitions', evaluated)]:
        text += 'inline constexpr int %s = %d;\n' % (name, value)
    text += 'inline constexpr double firstPerplexity = %.8f;\n' % first_perplexity
    text += 'inline constexpr double contextPerplexity = %.8f;\n' % context_perplexity
    text += array('first', first) + array('context', context)
    for name, rows in [('firstTotals', first), ('contextTotals', context)]:
        text += 'inline constexpr int %s[] = {%s};\n' % (name, ', '.join(str(sum(row)) for row in rows))
    text += '} // namespace composer::harmony_model\n'
    print('Source: %d rows, %d source IDs, %d collapsed changes' % (events, len(sequences), changes))
    print('Held out: %d source IDs, %d changes; perplexity uniform=36 first=%.3f context=%.3f' %
          (len(test_ids), evaluated, first_perplexity, context_perplexity))
    return text.encode('utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--download', action='store_true')
    args = parser.parse_args()
    if args.download:
        payload = urllib.request.urlopen(URL, timeout=30).read()
        if hashlib.sha256(payload).hexdigest() != ZIP_SHA:
            raise ValueError('Downloaded archive checksum mismatch')
        SOURCE.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(io.BytesIO(payload)) as archive:
            for name in ('jsbach_chorals_harmony.data', 'jsbach_chorals_harmony.names'):
                (SOURCE / name).write_bytes(archive.read(name))
    generated = build()
    if args.check:
        if OUTPUT.read_bytes() != generated:
            raise SystemExit('Embedded model differs; run scripts/train-harmony-model.py')
        print('Embedded model is reproducible.')
    else:
        OUTPUT.write_bytes(generated)
        print('Wrote', OUTPUT.relative_to(ROOT))


if __name__ == '__main__':
    main()
